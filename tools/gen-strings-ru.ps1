function Esc([string]$s) {
    $s = $s.Replace('&', '&amp;').Replace('<', '&lt;').Replace('>', '&gt;')
    $s = $s.Replace("'", "\'")
    if ($s -match '^\s' -or $s -match '\s$') { $s = '"' + $s + '"' }
    return $s
}
$lines = Get-Content $Tsv -Encoding UTF8
$out = New-Object System.Collections.Generic.List[string]
$out.Add('<?xml version="1.0" encoding="utf-8"?>')
$out.Add('<resources>')
foreach ($line in $lines) {
    $idx = $line.IndexOf("`t")
    if ($idx -lt 0) { continue }
    $key = $line.Substring(0, $idx)
    if ($key -eq 't160') { continue }  # протокольная строка, не в ресурсах
    $text = $line.Substring($idx + 1)
    if ($corr.ContainsKey($key)) {
        foreach ($rule in $corr[$key]) {
            $parts = $rule -split '~', 2
            $text = $text.Replace($parts[0], $parts[1])
        }
    }
    $out.Add(('    <string name="' + $key + '">' + (Esc $text) + '</string>'))
}
